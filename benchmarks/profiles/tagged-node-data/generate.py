from pathlib import Path
import re,hashlib,json,subprocess,sys
root=Path(__file__).resolve().parents[3];ast=root/'packages/tsc-go/internal/ast'
def write(path, text):
 if path.suffix=='.go':text=subprocess.check_output(['/tmp/tsc-toolchains/go/bin/gofmt'],input=text,text=True)
 if '--check' in sys.argv:assert path.read_text()==text, str(path)+' differs from generation'
 else:path.write_text(text)
files=[ast/'ast.go',ast/'ast_generated.go'];sources={p:subprocess.check_output(['git','show','649f1b7:'+str(p.relative_to(root))],cwd=root,text=True) for p in files}
names=sorted(set(re.findall(r'n\.data\.\(\*(\w+)\)', '\n'.join(sources.values()))))
assert 'SourceFile' in names and 'Identifier' in names and len(names)<65535
out=['// Generated by benchmarks/profiles/tagged-node-data/generate.py.\npackage ast\n\nimport "unsafe"\n\ntype nodePayloadTag uint16\nconst (\n nodePayloadNil nodePayloadTag = iota\n']
for name in names:out.append(' nodePayload'+name+'\n')
out.append(')\n\n// Keep a GC-visible pointer to the original concrete allocation. Copied Node\n// headers continue to refer to that allocation; Kind is not a concrete type tag.\nfunc (n *Node) setNodeData(data nodeData) {\n switch value := data.(type) {\n')
for name in names:out.append(f' case *{name}: n.dataPointer = unsafe.Pointer(value); n.dataTag = nodePayload{name}\n')
out.append(' default: panic("unsupported concrete node data")\n }\n}\n\nfunc (n *Node) nodeDataValue() nodeData {\n switch n.dataTag {\n case nodePayloadNil: return nil\n')
for name in names:out.append(f' case nodePayload{name}: return (*{name})(n.dataPointer)\n')
out.append(' default: panic("invalid concrete node data tag")\n }\n}\n')
for name in names:
 out.append(f'\nfunc (n *Node) payload{name}() *{name} {{\n if n.dataTag == nodePayload{name} {{ return (*{name})(n.dataPointer) }}\n // Preserve the checked assertion failure, including a nil payload.\n return n.nodeDataValue().(*{name})\n}}\n')
write(ast/'node_payload_generated.go',''.join(out))
for p,s in sources.items():
 s=re.sub(r'n\.data\.\(\*(\w+)\)',lambda m:'n.payload'+m[1]+'()',s)
 if p.name=='ast.go':
  s=s.replace('"sync/atomic"','"sync/atomic"\n "unsafe"')
  s=s.replace('n.data = data','n.setNodeData(data)')
  s=s.replace('Kind   Kind\n','Kind   Kind\n dataTag nodePayloadTag\n')
  s=s.replace('data   nodeData','dataPointer unsafe.Pointer')
  s=s.replace('n.data.', 'n.nodeDataValue().').replace('n.data)', 'n.nodeDataValue())')
  s=s.replace('node.data.', 'node.nodeDataValue().').replace('node.data)', 'node.nodeDataValue())')
 s=s.replace('n.nodeDataValue().setModifiers(modifiers)','(*Node)(n).nodeDataValue().setModifiers(modifiers)')
 write(p,s)
write(Path(__file__).resolve().parent/'types.json',json.dumps(names,indent=2)+'\n')
print('Generated',len(names),'concrete payload tags')
