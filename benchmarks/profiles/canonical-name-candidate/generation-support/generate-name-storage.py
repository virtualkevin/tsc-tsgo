"""Reproduce the local name-storage changes after pinned upstream generation.

Default is read-only --check. --write operates only on the explicitly supplied
root; unknown Identifier/encoder layouts are rejected instead of guessed.
"""
import argparse,hashlib,json,os,subprocess
from pathlib import Path
parser=argparse.ArgumentParser()
parser.add_argument('--root',type=Path,required=True)
parser.add_argument('--write',action='store_true')
parser.add_argument('--gofmt',default=os.environ.get('GOFMT','gofmt'))
args=parser.parse_args()
here=Path(__file__).resolve().parent
old='''type Identifier struct {
	PrimaryExpressionBase
	FlowNodeBase
	Text string
}

func (f *NodeFactory) NewIdentifier(text string) *Node {
	data := f.identifierArena.New()
	data.Text = text
	f.textCount++
	return f.newNode(KindIdentifier, data)
}

func (node *Identifier) Clone(f NodeFactoryCoercible) *Node {
	return cloneNode(f.AsNodeFactory().NewIdentifier(node.Text), node.AsNode(), f.AsNodeFactory().hooks)
}'''
new=old.replace('Text string','Text Name').replace('func (f *NodeFactory) NewIdentifier(text string) *Node {','func (f *NodeFactory) NewIdentifier(text string) *Node {\n\treturn f.NewIdentifierName(MakeName(text))\n}\n\nfunc (f *NodeFactory) NewIdentifierName(text Name) *Node {').replace('NewIdentifier(node.Text)','NewIdentifierName(node.Text)')
def replace_known(text,before,after):
 if text.count(after)==1 and before not in text:return text
 assert text.count(before)==1 and after not in text,'unrecognized generated source layout'
 return text.replace(before,after,1)
ast_path=args.root/'internal/ast/ast_generated.go'
encoder_path=args.root/'internal/api/encoder/encoder_generated.go'
outputs={ast_path:replace_known(ast_path.read_text(),old,new),encoder_path:replace_known(encoder_path.read_text(),'return strs.add(node.AsIdentifier().Text, node.Kind, node.Pos(), node.End())','return strs.add(node.AsIdentifier().Text.String(), node.Kind, node.Pos(), node.End())')}
def quote(data):
 pieces=[]
 for b in data:
  if b in [34,92]:pieces.append('\\'+chr(b))
  elif 32<=b<127:pieces.append(chr(b))
  else:pieces.append('\\x%02x'%b)
 return '"'+''.join(pieces)+'"'
entries=json.loads((here/'canonical-names.json').read_text())
assert len({e['bytes'] for e in entries})==len(entries)
assert len({e['function'] for e in entries})==len(entries)
# Preserve the current candidate's exact generated header during its frozen
# validation. Integrating this generator into the package must update provenance
# comments as part of the final reviewed source, before final validation.
pool='// Code generated by canonical-name-candidate/refine.go; DO NOT EDIT.\npackage ast\n\n'
for entry in sorted(entries,key=lambda e:bytes.fromhex(e['bytes'])):
 value=bytes.fromhex(entry['bytes']);name=entry['function']
 assert value and name=='CanonicalName'+hashlib.sha256(value).hexdigest()[:12]
 literal=quote(value)
 pool+=f'var cached{name} = MakeName({literal})\n// {name} returns the canonical key for {literal}.\nfunc {name}() Name {{ return cached{name} }}\n\n'
outputs[args.root/'internal/ast/canonical_names_generated.go']=pool
for path,text in outputs.items():
 formatted=subprocess.check_output([args.gofmt],input=text.encode()).decode()
 if args.write:path.write_text(formatted)
 else:assert path.read_text()==formatted,f'{path} needs regeneration'
print(json.dumps({'mode':'write' if args.write else 'check','generatedFiles':len(outputs),'constantNames':len(entries)}))
